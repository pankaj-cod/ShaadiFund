import "server-only";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { put } from "@vercel/blob";
import { getEnv } from "@/lib/env";

/**
 * Where image bytes live. The local driver is for development and tests only:
 * serverless hosts have no lasting disk. The blob driver stores photos in Vercel
 * Blob and serves them from its CDN.
 */
export interface MediaStorage {
  put(key: string, bytes: Buffer): Promise<{ url: string }>;
  /** Only the local driver serves files itself; blob URLs point straight at the CDN. */
  get(key: string): Promise<Buffer | null>;
}

const UPLOAD_DIR = path.join(process.cwd(), ".data", "uploads");

/** Storage keys are generated by us; this guards the read path against traversal. */
export const STORAGE_KEY_PATTERN = /^[0-9a-f-]{36}\.webp$/;

const localStorage: MediaStorage = {
  async put(key, bytes) {
    await mkdir(UPLOAD_DIR, { recursive: true });
    await writeFile(path.join(UPLOAD_DIR, key), bytes);
    return { url: `/api/media/file/${key}` };
  },
  async get(key) {
    if (!STORAGE_KEY_PATTERN.test(key)) return null;
    try {
      return await readFile(path.join(UPLOAD_DIR, key));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw error;
    }
  },
};

const ONE_YEAR_SECONDS = 365 * 24 * 60 * 60;

const blobStorage: MediaStorage = {
  async put(key, bytes) {
    // Keys are random UUIDs and files never change, so they can be cached for a year.
    const result = await put(`media/${key}`, bytes, {
      access: "public",
      contentType: "image/webp",
      addRandomSuffix: false,
      cacheControlMaxAge: ONE_YEAR_SECONDS,
      // Passed explicitly because the store's token may be under a prefixed name.
      token: getEnv().BLOB_READ_WRITE_TOKEN,
    });
    return { url: result.url };
  },
  async get() {
    return null;
  },
};

export function getMediaStorage(): MediaStorage {
  return getEnv().MEDIA_STORAGE === "blob" ? blobStorage : localStorage;
}
